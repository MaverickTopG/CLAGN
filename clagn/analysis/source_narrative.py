def generate_all_narratives(results_dir: str = './results/') -> None:
    """
    Generate science narratives for all top CLAGN candidates.

    Loads results from:
        - top_candidates.csv
        - advanced_drw_{source_id}.pkl
        - physics_{source_id}.pkl
        - enhanced_wise_{source_id}.pkl
        - gaia_{source_id}.pkl

    Saves:
        - narratives/{source_id}_narrative.txt

    Parameters
    ----------
    results_dir : str, path to results directory
    """
    import pickle

    results_path = Path(results_dir)
    narratives_dir = results_path / 'narratives'
    narratives_dir.mkdir(parents=True, exist_ok=True)

    candidates_file = results_path / 'top_candidates.csv'
    if not candidates_file.exists():
        logger.error(f"Candidates file not found: {candidates_file}")
        return

    try:
        candidates = pd.read_csv(candidates_file)
    except Exception as exc:
        logger.error(f"Failed to load candidates: {exc}")
        return

    logger.info(f"Generating narratives for {len(candidates)} candidates")

    for idx, row in candidates.iterrows():
        source_id = str(row.get('source_id', f'source_{idx}'))

        # Assemble results dictionary
        all_results = {'source_row': row.to_dict()}

        # Load DRW results
        for drw_path in [
            results_path / 'advanced_drw' / f'advanced_drw_{source_id}.pkl',
            results_path / f'drw_{source_id}.pkl',
        ]:
            if drw_path.exists():
                with open(drw_path, 'rb') as f:
                    drw_data = pickle.load(f)
                all_results['drw'] = drw_data.get('mcmc', drw_data)
                all_results['broken_drw'] = drw_data.get('broken_drw', {})
                break
        else:
            all_results['drw'] = {}
            all_results['broken_drw'] = {}

        # Load physics
        physics_path = results_path / 'physics' / f'physics_{source_id}.pkl'
        if physics_path.exists():
            with open(physics_path, 'rb') as f:
                all_results['physics'] = pickle.load(f)
        else:
            all_results['physics'] = {}

        # Load WISE light curve
        for wise_path in [
            results_path / 'wise_enhanced' / f'enhanced_wise_{source_id}.pkl',
            results_path / f'wise_{source_id}.pkl',
        ]:
            if wise_path.exists():
                with open(wise_path, 'rb') as f:
                    all_results['wise_lc'] = pickle.load(f)
                break
        else:
            all_results['wise_lc'] = {}

        # Load Gaia
        gaia_path = results_path / 'gaia_photometry' / f'gaia_{source_id}.pkl'
        if gaia_path.exists():
            with open(gaia_path, 'rb') as f:
                all_results['gaia'] = pickle.load(f)
        else:
            all_results['gaia'] = {}

        # Load changepoint
        cp_path = results_path / f'changepoint_{source_id}.pkl'
        if cp_path.exists():
            with open(cp_path, 'rb') as f:
                all_results['changepoint'] = pickle.load(f)
        else:
            all_results['changepoint'] = {}

        # Score
        all_results['score'] = _safe_float(row.get('clagn_score', row.get('score', np.nan)))
        all_results['score_max'] = 14.0

        try:
            narrative = generate_source_narrative(source_id, all_results)

            # Save
            txt_path = narratives_dir / f'{source_id}_narrative.txt'
            with open(txt_path, 'w', encoding='utf-8') as f:
                f.write(f"# CLAGN Candidate: {source_id}\n")
                f.write(f"# Generated by the CLAGN Pipeline\n\n")
                f.write(narrative)
                f.write("\n")

            logger.info(f"{source_id}: Narrative saved to {txt_path}")

        except Exception as exc:
            logger.error(f"{source_id}: Narrative generation failed: {exc}", exc_info=True)


def _safe_float(val, default: float = np.nan) -> float:
    """Safely convert a value to float."""
    try:
        f = float(val)
        return f if np.isfinite(f) else default
    except (TypeError, ValueError):
        return default
