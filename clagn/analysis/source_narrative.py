# ---------------------------------------------------------------------------
# Formatting helpers
# ---------------------------------------------------------------------------

def _sci_notation(x: float, sig_figs: int = 3) -> str:
    """Format a float in scientific notation suitable for prose."""
    if not np.isfinite(x) or x <= 0:
        return "N/A"
    exp = int(np.floor(np.log10(abs(x))))
    mantissa = x / 10.0 ** exp
    return f"{mantissa:.{sig_figs - 1}f} × 10^{exp}"


def _safe_float(val, default: float = np.nan) -> float:
    """Safely convert a value to float."""
    try:
        f = float(val)
        return f if np.isfinite(f) else default
    except (TypeError, ValueError):
        return default


